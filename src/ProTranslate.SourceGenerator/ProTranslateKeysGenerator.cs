    private static void AppendManifestEntries(StringBuilder builder, ImmutableArray<ManifestEntry> entries)
    {
        builder.AppendLine("    private static readonly ProTranslateProviderManifestEntry[] s_entries = new ProTranslateProviderManifestEntry[]");
        builder.AppendLine("    {");

        foreach (ManifestEntry entry in entries)
        {
            builder.Append("        new ProTranslateProviderManifestEntry(");
            builder.Append(FormatStringLiteral(entry.Key));
            builder.Append(", ");
            builder.Append(entry.Culture is null ? "null" : FormatStringLiteral(entry.Culture));
            builder.Append(", ");
            builder.Append(FormatStringLiteral(entry.SourceFile));
            builder.Append(", ");
            AppendIntArray(builder, entry.PlaceholderIndexes);
            builder.AppendLine("),");
        }

        builder.AppendLine("    };");
    }

