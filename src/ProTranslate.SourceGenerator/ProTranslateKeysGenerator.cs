    private static string? InferCulture(string path)
    {
        string fileName = Path.GetFileName(path);
        if ((fileName.EndsWith(".protranslate.json", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".i18next.json", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".i18n.json", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".arb", StringComparison.OrdinalIgnoreCase))
            || !fileName.StartsWith("Strings.", StringComparison.OrdinalIgnoreCase)
            || !fileName.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }

        const string prefix = "Strings.";
        const string suffix = ".json";
        string culture = fileName.Substring(prefix.Length, fileName.Length - prefix.Length - suffix.Length);
        return culture.Length == 0 ? null : culture;
    }

    private static ImmutableArray<int> ExtractPlaceholderIndexes(string value)
    {
        SortedSet<int>? indexes = null;

        for (int i = 0; i < value.Length; i++)
        {
            if (value[i] != '{')
            {
                continue;
            }

            if (i + 1 < value.Length && value[i + 1] == '{')
            {
                i++;
                continue;
            }

            int position = i + 1;
            while (position < value.Length && char.IsWhiteSpace(value[position]))
            {
                position++;
            }

            int digitStart = position;
            long index = 0;
            while (position < value.Length && char.IsDigit(value[position]))
            {
                index = (index * 10) + (value[position] - '0');
                if (index > int.MaxValue)
                {
                    break;
                }

                position++;
            }

            if (position == digitStart || index > int.MaxValue)
            {
                continue;
            }

            while (position < value.Length && char.IsWhiteSpace(value[position]))
            {
                position++;
            }

            if (position >= value.Length || (value[position] != '}' && value[position] != ',' && value[position] != ':'))
            {
                continue;
            }

            if (value[position] != '}' && !HasPlaceholderEnd(value, position + 1))
            {
                continue;
            }

            indexes ??= new SortedSet<int>();
            indexes.Add((int)index);
        }

        return indexes is null ? ImmutableArray<int>.Empty : indexes.ToImmutableArray();
    }

    private static bool HasPlaceholderEnd(string value, int start)
    {
        for (int i = start; i < value.Length; i++)
        {
            if (value[i] == '}' && i + 1 < value.Length && value[i + 1] == '}')
            {
                i++;
                continue;
            }

            if (value[i] == '}')
            {
                return true;
            }
        }

        return false;
    }

    private static string CreateIdentifier(string key)
    {
        var builder = new StringBuilder(key.Length);
        bool capitalizeNext = true;

        foreach (char character in key)
        {
            if (char.IsLetterOrDigit(character))
            {
                builder.Append(capitalizeNext ? char.ToUpperInvariant(character) : character);
                capitalizeNext = false;
            }
            else
            {
                capitalizeNext = true;
            }
        }

        if (builder.Length == 0 || char.IsDigit(builder[0]))
        {
            builder.Insert(0, '_');
        }

        string identifier = builder.ToString();
        return IsCSharpKeyword(identifier) ? "_" + identifier : identifier;
    }

    private static string FormatStringLiteral(string value)
    {
        return "\"" + value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n")
            .Replace("\t", "\\t") + "\"";
    }

    private static string ComputeStableHash(string value)
    {
        const uint offsetBasis = 2166136261;
        const uint prime = 16777619;

        uint hash = offsetBasis;
        foreach (char character in value)
        {
            hash ^= character;
            hash *= prime;
        }

        return hash.ToString("X8", System.Globalization.CultureInfo.InvariantCulture);
    }

