    }

    private static void AppendStringArray(StringBuilder builder, string fieldName, ImmutableArray<string> values)
    {
        builder.Append("    private static readonly string[] ");
        builder.Append(fieldName);
        builder.AppendLine(" = new string[]");
        builder.AppendLine("    {");

        foreach (string value in values)
        {
            builder.Append("        ");
            builder.Append(FormatStringLiteral(value));
            builder.AppendLine(",");
        }

        builder.AppendLine("    };");
    }

    private static void AppendIntArray(StringBuilder builder, ImmutableArray<int> values)
    {
        if (values.IsDefaultOrEmpty)
        {
            builder.Append("global::System.Array.Empty<int>()");
            return;
        }

        builder.Append("new int[] { ");
        for (int i = 0; i < values.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append(values[i].ToString(System.Globalization.CultureInfo.InvariantCulture));
        }

        builder.Append(" }");
    }

    private static CatalogFile ParseCatalogFile(AdditionalText file, System.Threading.CancellationToken cancellationToken)
    {
        SourceText? text = file.GetText(cancellationToken);
        if (text is null)
        {
            return new CatalogFile(file.Path, ImmutableArray<KeyEntry>.Empty, ImmutableArray<Diagnostic>.Empty);
        }

        if (IsResxCatalogFile(file.Path))
        {
            return ParseResxCatalogFile(file.Path, text);
        }

        if (IsAndroidResourceCatalogFile(file.Path))
        {
            return ParseAndroidCatalogFile(file.Path, text);
        }

        if (IsXliffCatalogFile(file.Path))
        {
            return ParseXliffCatalogFile(file.Path, text);
        }

        if (IsPoCatalogFile(file.Path))
        {
            return ParsePoCatalogFile(file.Path, text);
        }

        if (IsDelimitedCatalogFile(file.Path))
        {
            return ParseDelimitedCatalogFile(file.Path, text);
        }

        if (IsAppleStringsCatalogFile(file.Path))
        {
            return ParseAppleStringsCatalogFile(file.Path, text);
        }

        if (IsAppleStringsdictCatalogFile(file.Path))
        {
            return ParseAppleStringsdictCatalogFile(file.Path, text);
        }

        if (IsAppleXcstringsCatalogFile(file.Path))
        {
            return ParseAppleXcstringsCatalogFile(file.Path, text);
        }

        if (!IsJsonCatalogFile(file.Path))
        {
            return ParseTextCatalogFile(file.Path, text);
        }

        string content = text.ToString();
        int firstNonWhitespace = 0;
        while (firstNonWhitespace < content.Length && char.IsWhiteSpace(content[firstNonWhitespace]))
        {
            firstNonWhitespace++;
        }

        if (firstNonWhitespace >= content.Length || content[firstNonWhitespace] != '{')
        {
            return new CatalogFile(
                file.Path,
                ImmutableArray<KeyEntry>.Empty,
                ImmutableArray.Create(CreateInvalidJsonDiagnostic(file.Path, text, firstNonWhitespace, "Expected root object.")));
        }

        bool isArbCatalogFile = IsArbCatalogFile(file.Path);
        string? culture = null;
        if (isArbCatalogFile && TryFindJsonPropertyString(content, "@@locale", 0, content.Length, out string arbLocale))
        {
            culture = arbLocale;
        }

        return JsonCatalogParser.Parse(file.Path, text, InvalidJsonDescriptor, isArbCatalogFile, culture);
    }

    private static CatalogFile ParseTextCatalogFile(string path, SourceText text)
    {
        var keys = ImmutableArray.CreateBuilder<KeyEntry>();

        foreach (TextLine line in text.Lines)
        {
            string key = line.ToString().Trim();
            if (key.Length == 0 || key.StartsWith("#", StringComparison.Ordinal))
            {
                continue;
            }

            int offset = line.ToString().IndexOf(key, StringComparison.Ordinal);
            int position = line.Start + Math.Max(0, offset);
            keys.Add(new KeyEntry(key, path, text, position));
        }

        return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
    }

    private static CatalogFile ParseResxCatalogFile(string path, SourceText text)
    {
        try
        {
            XDocument document = XDocument.Parse(text.ToString(), LoadOptions.PreserveWhitespace);
            var keys = ImmutableArray.CreateBuilder<KeyEntry>();
            string? culture = InferResxCulture(path);

            foreach (XElement data in document.Descendants().Where(static element => element.Name.LocalName == "data"))
            {
                string? key = data.Attribute("name")?.Value;
                string? value = data.Elements().FirstOrDefault(static element => element.Name.LocalName == "value")?.Value;
                if (string.IsNullOrWhiteSpace(key) || value is null)
                {
                    continue;
                }

                keys.Add(CreateKeyEntry(path, text, key!, value, culture));
            }

            return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
        }
        catch (Exception ex) when (ex is System.Xml.XmlException or InvalidOperationException)
        {
            return CreateInvalidCatalogFile(path, text, ex.Message);
        }
    }

    private static CatalogFile ParseAndroidCatalogFile(string path, SourceText text)
    {
        try
        {
            XDocument document = XDocument.Parse(text.ToString(), LoadOptions.PreserveWhitespace);
            var keys = ImmutableArray.CreateBuilder<KeyEntry>();
            string? culture = InferAndroidCulture(path);

            foreach (XElement element in (document.Root?.Elements() ?? Enumerable.Empty<XElement>()))
            {
                string? key = element.Attribute("name")?.Value;
                if (string.IsNullOrWhiteSpace(key))
                {
                    continue;
                }

                if (element.Name.LocalName == "string")
                {
                    keys.Add(CreateKeyEntry(path, text, key!, element.Value, culture));
                }
                else if (element.Name.LocalName == "plurals")
                {
                    foreach (XElement item in element.Elements().Where(static child => child.Name.LocalName == "item"))
                    {
                        string? quantity = item.Attribute("quantity")?.Value;
                        if (!string.IsNullOrWhiteSpace(quantity))
                        {
                            keys.Add(CreateKeyEntry(path, text, key + "." + quantity, item.Value, culture));
                        }
                    }
                }
                else if (element.Name.LocalName == "string-array")
                {
                    int index = 0;
                    foreach (XElement item in element.Elements().Where(static child => child.Name.LocalName == "item"))
                    {
                        keys.Add(CreateKeyEntry(path, text, key + "[" + index.ToString(System.Globalization.CultureInfo.InvariantCulture) + "]", item.Value, culture));
                        index++;
                    }
                }
            }

            return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
        }
        catch (Exception ex) when (ex is System.Xml.XmlException or InvalidOperationException)
        {
            return CreateInvalidCatalogFile(path, text, ex.Message);
        }
    }

    private static CatalogFile ParseXliffCatalogFile(string path, SourceText text)
    {
        try
        {
            XDocument document = XDocument.Parse(text.ToString(), LoadOptions.PreserveWhitespace);
            XElement root = document.Root ?? throw new InvalidOperationException("XLIFF document is missing a root element.");
            var keys = ImmutableArray.CreateBuilder<KeyEntry>();
            string version = root.Attribute("version")?.Value ?? string.Empty;

            if (version.StartsWith("1.", StringComparison.Ordinal))
            {
                foreach (XElement file in root.Descendants().Where(static element => element.Name.LocalName == "file"))
                {
                    string? culture = file.Attribute("target-language")?.Value;
                    int index = 0;
                    foreach (XElement unit in file.Descendants().Where(static element => element.Name.LocalName == "trans-unit"))
                    {
                        string key = unit.Attribute("resname")?.Value
                            ?? unit.Attribute("id")?.Value
                            ?? "TransUnit" + index.ToString(System.Globalization.CultureInfo.InvariantCulture);
                        string? target = unit.Elements().FirstOrDefault(static element => element.Name.LocalName == "target")?.Value;
                        string? source = unit.Elements().FirstOrDefault(static element => element.Name.LocalName == "source")?.Value;
                        keys.Add(CreateKeyEntry(path, text, key, target ?? source ?? string.Empty, culture));
                        index++;
                    }
                }
            }
            else
            {
                string? culture = root.Attribute("trgLang")?.Value;
                int index = 0;
                foreach (XElement unit in root.Descendants().Where(static element => element.Name.LocalName == "unit"))
                {
                    string key = unit.Attribute("name")?.Value
                        ?? unit.Attribute("id")?.Value
                        ?? "Unit" + index.ToString(System.Globalization.CultureInfo.InvariantCulture);
                    foreach (XElement segment in unit.Descendants().Where(static element => element.Name.LocalName == "segment"))
                    {
                        string? target = segment.Elements().FirstOrDefault(static element => element.Name.LocalName == "target")?.Value;
                        string? source = segment.Elements().FirstOrDefault(static element => element.Name.LocalName == "source")?.Value;
                        keys.Add(CreateKeyEntry(path, text, key, target ?? source ?? string.Empty, culture));
                    }

                    index++;
                }
            }

            return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
        }
        catch (Exception ex) when (ex is System.Xml.XmlException or InvalidOperationException)
        {
            return CreateInvalidCatalogFile(path, text, ex.Message);
        }
    }

    private static CatalogFile ParsePoCatalogFile(string path, SourceText text)
    {
        var keys = ImmutableArray.CreateBuilder<KeyEntry>();
        string? culture = InferCultureFromPath(path, ".po") ?? InferCultureFromPath(path, ".pot");

        foreach (GeneratorPoEntry entry in ParsePoEntries(text.ToString()))
        {
            if (entry.MsgId.Length == 0)
            {
                string headerCulture = ReadPoHeaderLanguage(entry.MsgStr);
                if (headerCulture.Length > 0)
                {
                    culture = headerCulture;
                }

                continue;
            }

            string key = entry.Context is null ? entry.MsgId : entry.Context + "\u0004" + entry.MsgId;
            if (entry.PluralTranslations.Count == 0)
            {
                keys.Add(CreateKeyEntry(path, text, key, entry.MsgStr.Length == 0 ? entry.MsgId : entry.MsgStr, culture));
            }
            else
            {
                int pluralFormCount = entry.PluralTranslations.Keys.DefaultIfEmpty(-1).Max() + 1;
                foreach (KeyValuePair<int, string> plural in entry.PluralTranslations.OrderBy(static value => value.Key))
                {
                    string category = GetPoPluralCategory(plural.Key, pluralFormCount);
                    keys.Add(CreateKeyEntry(path, text, key + "." + category, plural.Value, culture));
                }
            }
        }

        return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
    }

    private static CatalogFile ParseDelimitedCatalogFile(string path, SourceText text)
    {
        char delimiter = path.EndsWith(".tsv", StringComparison.OrdinalIgnoreCase) ? '\t' : ',';
        List<string[]> rows = ParseDelimitedRows(text.ToString(), delimiter);
        if (rows.Count == 0)
        {
            return new CatalogFile(path, ImmutableArray<KeyEntry>.Empty, ImmutableArray<Diagnostic>.Empty);
        }

        Dictionary<string, int> columns = rows[0]
            .Select(static (name, index) => new { Name = name.Trim().ToLowerInvariant(), Index = index })
            .ToDictionary(static item => item.Name, static item => item.Index, StringComparer.Ordinal);

        if (!columns.ContainsKey("key") || !columns.ContainsKey("value"))
        {
            return CreateInvalidCatalogFile(path, text, "Delimited translation catalogs require key and value columns.");
        }

        var keys = ImmutableArray.CreateBuilder<KeyEntry>();
        for (int i = 1; i < rows.Count; i++)
        {
            string[] row = rows[i];
            string key = GetColumn(row, columns, "key");
            if (key.Length == 0)
            {
                continue;
            }

            keys.Add(CreateKeyEntry(path, text, key, GetColumn(row, columns, "value"), GetColumn(row, columns, "culture", null)));
        }

        return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
    }

    private static CatalogFile ParseAppleStringsCatalogFile(string path, SourceText text)
    {
        var keys = ImmutableArray.CreateBuilder<KeyEntry>();
        string content = text.ToString();
        string? culture = InferAppleCulture(path);
        int index = 0;

        while (index < content.Length)
        {
            SkipAppleWhitespaceAndComments(content, ref index);
            if (index >= content.Length)
            {
                break;
            }

            int keyPosition = index;
            if (!TryReadAppleQuotedString(content, ref index, out string key))
            {
                break;
            }

            SkipAppleWhitespaceAndComments(content, ref index);
            if (index >= content.Length || content[index] != '=')
            {
                break;
            }

            index++;
            SkipAppleWhitespaceAndComments(content, ref index);
            if (!TryReadAppleQuotedString(content, ref index, out string value))
            {
                break;
            }

            keys.Add(new KeyEntry(key, path, text, keyPosition, value, culture));
            while (index < content.Length && content[index] != ';')
            {
                index++;
            }

            if (index < content.Length)
            {
                index++;
            }
        }

        return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
    }

    private static CatalogFile ParseAppleStringsdictCatalogFile(string path, SourceText text)
    {
        try
        {
            XDocument document = XDocument.Parse(text.ToString(), LoadOptions.PreserveWhitespace);
            XElement? dict = document.Root?.Elements().FirstOrDefault(static element => element.Name.LocalName == "dict");
            if (dict is null)
            {
                return new CatalogFile(path, ImmutableArray<KeyEntry>.Empty, ImmutableArray<Diagnostic>.Empty);
            }

            var keys = ImmutableArray.CreateBuilder<KeyEntry>();
            string? culture = InferAppleCulture(path);
            Dictionary<string, XElement> top = ReadPlistDict(dict);
            foreach (KeyValuePair<string, XElement> entry in top)
            {
                Dictionary<string, XElement> valueDict = ReadPlistDict(entry.Value);
                foreach (KeyValuePair<string, XElement> child in valueDict)
                {
                    if (child.Value.Name.LocalName != "dict")
                    {
                        continue;
                    }

                    Dictionary<string, XElement> pluralDict = ReadPlistDict(child.Value);
                    if (!pluralDict.TryGetValue("NSStringFormatSpecTypeKey", out XElement? spec)
                        || !string.Equals(spec.Value, "NSStringPluralRuleType", StringComparison.Ordinal))
                    {
                        continue;
                    }

                    foreach (string category in new[] { "zero", "one", "two", "few", "many", "other" })
                    {
                        if (pluralDict.TryGetValue(category, out XElement? localized))
                        {
                            keys.Add(CreateKeyEntry(path, text, entry.Key + "." + category, localized.Value, culture));
                        }
                    }
                }
            }

            return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
        }
        catch (Exception ex) when (ex is System.Xml.XmlException or InvalidOperationException)
        {
            return CreateInvalidCatalogFile(path, text, ex.Message);
        }
    }

    private static CatalogFile ParseAppleXcstringsCatalogFile(string path, SourceText text)
    {
        string content = text.ToString();
        if (!TryFindJsonPropertyObject(content, "strings", out int start, out int end))
        {
            return new CatalogFile(path, ImmutableArray<KeyEntry>.Empty, ImmutableArray<Diagnostic>.Empty);
        }

        var keys = ImmutableArray.CreateBuilder<KeyEntry>();
        int position = start + 1;
        while (position < end)
        {
            SkipJsonWhitespace(content, ref position);
            if (position >= end || content[position] == '}')
            {
                break;
            }

            int keyPosition = position;
            if (!TryReadJsonString(content, ref position, out string key))
            {
                break;
            }

            SkipJsonWhitespace(content, ref position);
            if (position >= end || content[position] != ':')
            {
                break;
            }

            position++;
            SkipJsonWhitespace(content, ref position);
            if (!TryReadJsonValueSpan(content, ref position, out int objectStart, out int objectEnd))
            {
                break;
            }

            ParseXcstringsLocalizations(path, text, content, key, keyPosition, objectStart, objectEnd, keys);
            SkipJsonWhitespace(content, ref position);
            if (position < end && content[position] == ',')
            {
                position++;
            }
        }

        return new CatalogFile(path, keys.ToImmutable(), ImmutableArray<Diagnostic>.Empty);
    }

    private static void ParseXcstringsLocalizations(
        string path,
        SourceText text,
        string content,
        string key,
        int keyPosition,
        int objectStart,
        int objectEnd,
        ImmutableArray<KeyEntry>.Builder keys)
    {
        if (!TryFindJsonPropertyObject(content, "localizations", objectStart, objectEnd, out int localizationsStart, out int localizationsEnd))
        {
            return;
        }

        int position = localizationsStart + 1;
        while (position < localizationsEnd)
        {
            SkipJsonWhitespace(content, ref position);
            if (position >= localizationsEnd || content[position] == '}')
            {
                break;
            }

            if (!TryReadJsonString(content, ref position, out string culture))
            {
                break;
            }

            SkipJsonWhitespace(content, ref position);
            if (position >= localizationsEnd || content[position] != ':')
            {
                break;
            }

            position++;
            SkipJsonWhitespace(content, ref position);
            if (!TryReadJsonValueSpan(content, ref position, out int localizationStart, out int localizationEnd))
            {
                break;
            }

            if (TryGetXcstringsStringUnitValue(content, localizationStart, localizationEnd, out string value))
            {
                keys.Add(new KeyEntry(key, path, text, keyPosition, value, culture));
            }

            ParseXcstringsVariationValues(path, text, content, key, keyPosition, culture, localizationStart, localizationEnd, keys);

            SkipJsonWhitespace(content, ref position);
            if (position < localizationsEnd && content[position] == ',')
            {
                position++;
            }
        }
    }

    private static bool TryGetXcstringsStringUnitValue(string content, int objectStart, int objectEnd, out string value)
    {
        if (TryFindJsonPropertyObject(content, "stringUnit", objectStart, objectEnd, out int unitStart, out int unitEnd)
            && TryFindJsonPropertyString(content, "value", unitStart, unitEnd, out value))
        {
            return true;
        }

        return TryFindJsonPropertyString(content, "value", objectStart, objectEnd, out value);
    }

    private static void ParseXcstringsVariationValues(
        string path,
        SourceText text,
        string content,
        string key,
        int keyPosition,
        string culture,
        int localizationStart,
        int localizationEnd,
        ImmutableArray<KeyEntry>.Builder keys)
    {
        if (!TryFindJsonPropertyObject(content, "variations", localizationStart, localizationEnd, out int variationsStart, out int variationsEnd))
        {
            return;
        }

        int dimensionPosition = variationsStart + 1;
        while (dimensionPosition < variationsEnd)
        {
            SkipJsonWhitespace(content, ref dimensionPosition);
            if (dimensionPosition >= variationsEnd || content[dimensionPosition] == '}')
            {
                break;
            }

            if (!TryReadJsonString(content, ref dimensionPosition, out _))
            {
                break;
            }

            SkipJsonWhitespace(content, ref dimensionPosition);
            if (dimensionPosition >= variationsEnd || content[dimensionPosition] != ':')
            {
                break;
            }

            dimensionPosition++;
            SkipJsonWhitespace(content, ref dimensionPosition);
            if (!TryReadJsonValueSpan(content, ref dimensionPosition, out int dimensionStart, out int dimensionEnd))
            {
                break;
            }

            ParseXcstringsVariationDimension(path, text, content, key, keyPosition, culture, dimensionStart, dimensionEnd, keys);
            SkipJsonWhitespace(content, ref dimensionPosition);
            if (dimensionPosition < variationsEnd && content[dimensionPosition] == ',')
            {
                dimensionPosition++;
            }
        }
    }

    private static void ParseXcstringsVariationDimension(
        string path,
        SourceText text,
        string content,
        string key,
        int keyPosition,
        string culture,
        int dimensionStart,
        int dimensionEnd,
        ImmutableArray<KeyEntry>.Builder keys)
    {
        int variationPosition = dimensionStart + 1;
        while (variationPosition < dimensionEnd)
        {
            SkipJsonWhitespace(content, ref variationPosition);
            if (variationPosition >= dimensionEnd || content[variationPosition] == '}')
            {
                break;
            }

            if (!TryReadJsonString(content, ref variationPosition, out string variationName))
            {
                break;
            }

            SkipJsonWhitespace(content, ref variationPosition);
            if (variationPosition >= dimensionEnd || content[variationPosition] != ':')
            {
                break;
            }

            variationPosition++;
            SkipJsonWhitespace(content, ref variationPosition);
            if (!TryReadJsonValueSpan(content, ref variationPosition, out int variationStart, out int variationEnd))
            {
                break;
            }

            if (TryGetXcstringsStringUnitValue(content, variationStart, variationEnd, out string value))
            {
                keys.Add(new KeyEntry(key + "." + variationName, path, text, keyPosition, value, culture));
            }

            SkipJsonWhitespace(content, ref variationPosition);
            if (variationPosition < dimensionEnd && content[variationPosition] == ',')
            {
                variationPosition++;
            }
        }
    }

    private static KeyEntry CreateKeyEntry(string path, SourceText text, string key, string value, string? culture = null)
    {
        string content = text.ToString();
        int position = content.IndexOf(key, StringComparison.Ordinal);
        return new KeyEntry(key, path, text, Math.Max(0, position), value, culture);
    }

