    private static string? InferResxCulture(string path) => InferCultureFromPath(path, ".resx");

    private static string? InferCultureFromPath(string path, string extension)
    {
        string fileName = Path.GetFileName(path);
        if (!fileName.EndsWith(extension, StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }

        string withoutExtension = fileName.Substring(0, fileName.Length - extension.Length);
        int separator = withoutExtension.LastIndexOf('.');
        return separator < 0 || separator == withoutExtension.Length - 1
            ? null
            : withoutExtension.Substring(separator + 1);
    }

    private static string? InferAndroidCulture(string path)
    {
        string? directory = Path.GetFileName(Path.GetDirectoryName(path));
        if (directory is null || !directory.StartsWith("values-", StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }

        string qualifier = directory.Substring("values-".Length);
        if (qualifier.StartsWith("b+", StringComparison.OrdinalIgnoreCase))
        {
            string[] bcp47Parts = qualifier.Split(new[] { '+' })
                .Where(static part => part.Length > 0)
                .ToArray();
            return bcp47Parts.Length > 1 ? NormalizeAndroidBcp47Culture(bcp47Parts.Skip(1)) : null;
        }

        string[] parts = qualifier.Split(new[] { '-' })
            .Where(static part => part.Length > 0)
            .ToArray();
        if (parts.Length == 0 || !IsAndroidLanguageQualifier(parts[0]))
        {
            return null;
        }

        var cultureParts = new List<string> { parts[0].ToLowerInvariant() };
        for (int i = 1; i < parts.Length; i++)
        {
            string part = parts[i];
            if (part.Length == 4 && part.All(char.IsLetter))
            {
                cultureParts.Add(char.ToUpperInvariant(part[0]) + part.Substring(1).ToLowerInvariant());
            }
            else if (part.Length == 3 && (part[0] == 'r' || part[0] == 'R') && part.Substring(1).All(char.IsLetterOrDigit))
            {
                cultureParts.Add(part.Substring(1).ToUpperInvariant());
            }
            else
            {
                break;
            }
        }

        return string.Join("-", cultureParts);
    }

    private static bool IsAndroidLanguageQualifier(string value) =>
        (value.Length == 2 || value.Length == 3) && value.All(char.IsLetter);

    private static string NormalizeAndroidBcp47Culture(IEnumerable<string> parts)
    {
        var normalized = new List<string>();
        int index = 0;
        foreach (string part in parts)
        {
            if (part.Length == 0)
            {
                continue;
            }

            if (index == 0)
            {
                normalized.Add(part.ToLowerInvariant());
            }
            else if (part.Length == 2 || part.Length == 3)
            {
                normalized.Add(part.ToUpperInvariant());
            }
            else if (part.Length == 4)
            {
                normalized.Add(char.ToUpperInvariant(part[0]) + part.Substring(1).ToLowerInvariant());
            }
            else
            {
                normalized.Add(part);
            }

            index++;
        }

        return normalized.Count == 0 ? string.Empty : string.Join("-", normalized);
    }

    private static string GetPoPluralCategory(int pluralIndex, int pluralFormCount)
    {
        if (pluralFormCount <= 2)
        {
            return pluralIndex == 0 ? "one" : "other";
        }

        return pluralFormCount switch
        {
            3 => pluralIndex switch
            {
                0 => "one",
                1 => "few",
                2 => "many",
                _ => "plural" + pluralIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)
            },
            4 => pluralIndex switch
            {
                0 => "one",
                1 => "two",
                2 => "few",
                3 => "other",
                _ => "plural" + pluralIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)
            },
            6 => pluralIndex switch
            {
                0 => "zero",
                1 => "one",
                2 => "two",
                3 => "few",
                4 => "many",
                5 => "other",
                _ => "plural" + pluralIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)
            },
            _ => "plural" + pluralIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)
        };
    }

    private static string? InferAppleCulture(string path)
    {
        string? directory = Path.GetFileName(Path.GetDirectoryName(path));
        if (directory is not null && directory.EndsWith(".lproj", StringComparison.OrdinalIgnoreCase))
        {
            return directory.Substring(0, directory.Length - ".lproj".Length);
        }

        return InferCultureFromPath(path, Path.GetExtension(path));
    }

    private static Dictionary<string, XElement> ReadPlistDict(XElement dict)
    {
        var values = new Dictionary<string, XElement>(StringComparer.Ordinal);
        XElement? key = null;
        foreach (XElement child in dict.Elements())
        {
            if (child.Name.LocalName == "key")
            {
                key = child;
                continue;
            }

            if (key is not null)
            {
                values[key.Value] = child;
                key = null;
            }
        }

        return values;
    }

    private static IEnumerable<GeneratorPoEntry> ParsePoEntries(string content)
    {
        var entries = new List<GeneratorPoEntry>();
        var current = new GeneratorPoEntry();
        string? active = null;
        int? pluralIndex = null;

        foreach (string rawLine in content.Replace("\r\n", "\n").Split('\n'))
        {
            string line = rawLine.Trim();
            if (line.Length == 0)
            {
                if (current.HasContent)
                {
                    entries.Add(current);
                    current = new GeneratorPoEntry();
                    active = null;
                    pluralIndex = null;
                }

                continue;
            }

            if (line.StartsWith("msgctxt", StringComparison.Ordinal))
            {
                current.Context = ReadPoString(line.Substring("msgctxt".Length).Trim());
                active = "msgctxt";
                pluralIndex = null;
            }
            else if (line.StartsWith("msgid_plural", StringComparison.Ordinal))
            {
                current.MsgIdPlural = ReadPoString(line.Substring("msgid_plural".Length).Trim());
                active = "msgid_plural";
                pluralIndex = null;
            }
            else if (line.StartsWith("msgid", StringComparison.Ordinal))
            {
                current.MsgId = ReadPoString(line.Substring("msgid".Length).Trim());
                active = "msgid";
                pluralIndex = null;
            }
            else if (line.StartsWith("msgstr[", StringComparison.Ordinal))
            {
                int end = line.IndexOf(']');
                if (end > 7 && int.TryParse(line.Substring(7, end - 7), out int parsedIndex))
                {
                    pluralIndex = parsedIndex;
                    current.PluralTranslations[parsedIndex] = ReadPoString(line.Substring(end + 1).Trim());
                    active = "msgstr";
                }
            }
            else if (line.StartsWith("msgstr", StringComparison.Ordinal))
            {
                current.MsgStr = ReadPoString(line.Substring("msgstr".Length).Trim());
                active = "msgstr";
                pluralIndex = null;
            }
            else if (line.StartsWith("\"", StringComparison.Ordinal) && active is not null)
            {
                string fragment = ReadPoString(line);
                if (active == "msgctxt")
                {
                    current.Context += fragment;
                }
                else if (active == "msgid")
                {
                    current.MsgId += fragment;
                }
                else if (active == "msgid_plural")
                {
                    current.MsgIdPlural += fragment;
                }
                else if (active == "msgstr" && pluralIndex is not null)
                {
                    current.PluralTranslations[pluralIndex.Value] += fragment;
                }
                else if (active == "msgstr")
                {
                    current.MsgStr += fragment;
                }
            }
        }

        if (current.HasContent)
        {
            entries.Add(current);
        }

        return entries;
    }

    private static string ReadPoHeaderLanguage(string header)
    {
        foreach (string line in header.Split('\n'))
        {
            if (line.StartsWith("Language:", StringComparison.OrdinalIgnoreCase))
            {
                return line.Substring("Language:".Length).Trim();
            }
        }

        return string.Empty;
    }

    private static string ReadPoString(string token)
    {
        token = token.Trim();
        if (token.Length < 2 || token[0] != '"' || token[token.Length - 1] != '"')
        {
            return string.Empty;
        }

        string inner = token.Substring(1, token.Length - 2);
        var builder = new StringBuilder(inner.Length);
        for (int i = 0; i < inner.Length; i++)
        {
            char current = inner[i];
            if (current == '\\' && i + 1 < inner.Length)
            {
                char escaped = inner[++i];
                builder.Append(escaped switch
                {
                    'n' => '\n',
                    'r' => '\r',
                    't' => '\t',
                    '"' => '"',
                    '\\' => '\\',
                    _ => escaped
                });
            }
            else
            {
                builder.Append(current);
            }
        }

        return builder.ToString();
    }

    private static List<string[]> ParseDelimitedRows(string content, char delimiter)
    {
        var rows = new List<string[]>();
        var row = new List<string>();
        var field = new StringBuilder();
        bool quoted = false;

        for (int i = 0; i < content.Length; i++)
        {
            char current = content[i];
            if (quoted)
            {
                if (current == '"' && i + 1 < content.Length && content[i + 1] == '"')
                {
                    field.Append('"');
                    i++;
                }
                else if (current == '"')
                {
                    quoted = false;
                }
                else
                {
                    field.Append(current);
                }

                continue;
            }

            if (current == '"')
            {
                quoted = true;
            }
            else if (current == delimiter)
            {
                row.Add(field.ToString());
                field.Clear();
            }
            else if (current == '\n')
            {
                row.Add(field.ToString());
                field.Clear();
                rows.Add(row.ToArray());
                row.Clear();
            }
            else if (current != '\r')
            {
                field.Append(current);
            }
        }

        row.Add(field.ToString());
        if (row.Count > 1 || row[0].Length > 0)
        {
            rows.Add(row.ToArray());
        }

        return rows;
    }

    private static string GetColumn(string[] row, Dictionary<string, int> columns, string name, string? fallback = "")
    {
        return columns.TryGetValue(name, out int index) && index < row.Length ? row[index] : fallback ?? string.Empty;
    }

    private static void SkipAppleWhitespaceAndComments(string text, ref int index)
    {
        while (index < text.Length)
        {
            if (char.IsWhiteSpace(text[index]))
            {
                index++;
                continue;
            }

            if (index + 1 < text.Length && text[index] == '/' && text[index + 1] == '*')
            {
                int end = text.IndexOf("*/", index + 2, StringComparison.Ordinal);
                index = end < 0 ? text.Length : end + 2;
                continue;
            }

            if (index + 1 < text.Length && text[index] == '/' && text[index + 1] == '/')
            {
                int end = text.IndexOf('\n', index + 2);
                index = end < 0 ? text.Length : end + 1;
                continue;
            }

            break;
        }
    }

    private static bool TryReadAppleQuotedString(string text, ref int index, out string value)
    {
        value = string.Empty;
        if (index >= text.Length || text[index] != '"')
        {
            return false;
        }

        return TryReadJsonString(text, ref index, out value);
    }

    private static bool TryFindJsonPropertyObject(string content, string propertyName, out int start, out int end) =>
        TryFindJsonPropertyObject(content, propertyName, 0, content.Length, out start, out end);

    private static bool TryFindJsonPropertyObject(string content, string propertyName, int searchStart, int searchEnd, out int start, out int end)
    {
        start = 0;
        end = 0;
        int position = searchStart;
        while (position < searchEnd)
        {
            SkipJsonWhitespace(content, ref position);
            if (!TryReadJsonString(content, ref position, out string name))
            {
                position++;
                continue;
            }

            SkipJsonWhitespace(content, ref position);
            if (position >= searchEnd || content[position] != ':')
            {
                continue;
            }

            position++;
            SkipJsonWhitespace(content, ref position);
            if (name == propertyName && position < searchEnd && content[position] == '{')
            {
                int valuePosition = position;
                if (TryReadJsonValueSpan(content, ref valuePosition, out start, out end))
                {
                    return true;
                }
            }

            TryReadJsonValueSpan(content, ref position, out _, out _);
        }

        return false;
    }

    private static bool TryFindJsonPropertyString(string content, string propertyName, int searchStart, int searchEnd, out string value)
    {
        value = string.Empty;
        int position = searchStart;
        while (position < searchEnd)
        {
            SkipJsonWhitespace(content, ref position);
            if (!TryReadJsonString(content, ref position, out string name))
            {
                position++;
                continue;
            }

            SkipJsonWhitespace(content, ref position);
            if (position >= searchEnd || content[position] != ':')
            {
                continue;
            }

            position++;
            SkipJsonWhitespace(content, ref position);
            if (name == propertyName && TryReadJsonString(content, ref position, out value))
            {
                return true;
            }

            TryReadJsonValueSpan(content, ref position, out _, out _);
        }

        return false;
    }

    private static bool TryReadJsonValueSpan(string content, ref int position, out int start, out int end)
    {
        SkipJsonWhitespace(content, ref position);
        start = position;
        end = position;
        if (position >= content.Length)
        {
            return false;
        }

        if (content[position] == '{')
        {
            return TryReadBalancedJson(content, ref position, '{', '}', out start, out end);
        }

        if (content[position] == '[')
        {
            return TryReadBalancedJson(content, ref position, '[', ']', out start, out end);
        }

        if (content[position] == '"')
        {
            if (!TryReadJsonString(content, ref position, out _))
            {
                return false;
            }

            end = position;
            return true;
        }

        while (position < content.Length && content[position] != ',' && content[position] != '}' && content[position] != ']')
        {
            position++;
        }

        end = position;
        return true;
    }

    private static bool TryReadBalancedJson(string content, ref int position, char open, char close, out int start, out int end)
    {
        start = position;
        end = position;
        int depth = 0;
        bool inString = false;
        bool escaped = false;

        while (position < content.Length)
        {
            char current = content[position++];
            if (inString)
            {
                if (escaped)
                {
                    escaped = false;
                }
                else if (current == '\\')
                {
                    escaped = true;
                }
                else if (current == '"')
                {
                    inString = false;
                }

                continue;
            }

            if (current == '"')
            {
                inString = true;
            }
            else if (current == open)
            {
                depth++;
            }
            else if (current == close)
            {
                depth--;
                if (depth == 0)
                {
                    end = position;
                    return true;
                }
            }
        }

        return false;
    }

    private static bool TryReadJsonString(string content, ref int position, out string value)
    {
        value = string.Empty;
        if (position >= content.Length || content[position] != '"')
        {
            return false;
        }

        position++;
        var builder = new StringBuilder();
        while (position < content.Length)
        {
            char current = content[position++];
            if (current == '"')
            {
                value = builder.ToString();
                return true;
            }

            if (current == '\\' && position < content.Length)
            {
                char escaped = content[position++];
                builder.Append(escaped switch
                {
                    'b' => '\b',
                    'f' => '\f',
                    'n' => '\n',
                    'r' => '\r',
                    't' => '\t',
                    '"' => '"',
                    '\\' => '\\',
                    '/' => '/',
                    'u' when TryReadUnicodeEscape(content, ref position, out char unicodeCharacter) => unicodeCharacter,
                    _ => escaped
                });
            }
            else
            {
                builder.Append(current);
            }
        }

        return false;
    }

    private static bool TryReadUnicodeEscape(string content, ref int position, out char value)
    {
        value = '\0';
        if (position + 4 > content.Length)
        {
            return false;
        }

        int codePoint = 0;
        for (int i = 0; i < 4; i++)
        {
            int digit = HexValue(content[position + i]);
            if (digit < 0)
            {
                return false;
            }

            codePoint = (codePoint << 4) + digit;
        }

        position += 4;
        value = (char)codePoint;
        return true;
    }

    private static int HexValue(char character)
    {
        if (character >= '0' && character <= '9')
        {
            return character - '0';
        }

        if (character >= 'a' && character <= 'f')
        {
            return character - 'a' + 10;
        }

        if (character >= 'A' && character <= 'F')
        {
            return character - 'A' + 10;
        }

        return -1;
    }

    private static void SkipJsonWhitespace(string content, ref int position)
    {
        while (position < content.Length && char.IsWhiteSpace(content[position]))
        {
            position++;
        }
    }

    private static CatalogModel CreateCatalogModel(ImmutableArray<CatalogFile> files)
    {
        var diagnostics = ImmutableArray.CreateBuilder<Diagnostic>();
        var allKeys = ImmutableArray.CreateBuilder<string>();

        foreach (CatalogFile file in files.OrderBy(file => file.Path, StringComparer.OrdinalIgnoreCase))
        {
            diagnostics.AddRange(file.Diagnostics);
            allKeys.AddRange(file.Keys.Select(key => key.Key));

            foreach (IGrouping<string, KeyEntry> group in file.Keys.GroupBy(key => key.Key, StringComparer.Ordinal))
            {
                KeyEntry[] duplicates = group.Skip(1).ToArray();
                foreach (KeyEntry duplicate in duplicates)
                {
                    diagnostics.Add(Diagnostic.Create(
                        DuplicateKeyDescriptor,
                        duplicate.Location,
                        duplicate.Key,
                        Path.GetFileName(file.Path)));
                }
            }
        }

        ImmutableArray<string> keys = allKeys
            .Distinct(StringComparer.Ordinal)
            .OrderBy(key => key, StringComparer.Ordinal)
            .ToImmutableArray();

        ImmutableArray<ManifestEntry> manifestEntries = files
            .SelectMany(static file => file.Keys.Select(static key => key.ToManifestEntry()))
            .OrderBy(static entry => entry.Key, StringComparer.Ordinal)
            .ThenBy(static entry => entry.Culture ?? string.Empty, StringComparer.Ordinal)
            .ThenBy(static entry => entry.SourceFile, StringComparer.Ordinal)
            .ThenBy(static entry => string.Join(",", entry.PlaceholderIndexes.Select(static value => value.ToString(System.Globalization.CultureInfo.InvariantCulture)).ToArray()), StringComparer.Ordinal)
            .ToImmutableArray();

        ImmutableArray<string> cultures = manifestEntries
            .Select(static entry => entry.Culture)
            .Where(static culture => culture is not null)
            .Select(static culture => culture!)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static culture => culture, StringComparer.Ordinal)
            .ToImmutableArray();

        ImmutableArray<string> sourceFiles = manifestEntries
            .Select(static entry => entry.SourceFile)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static sourceFile => sourceFile, StringComparer.Ordinal)
            .ToImmutableArray();

        ImmutableArray<ProviderEntry> providerEntries = files
            .SelectMany(static file => file.Keys)
            .Where(static key => key.Value is not null)
            .Select(static key => new ProviderEntry(key.Key, key.Culture, key.Value!))
            .OrderBy(static entry => entry.Key, StringComparer.Ordinal)
            .ThenBy(static entry => entry.Culture ?? string.Empty, StringComparer.Ordinal)
            .ThenBy(static entry => entry.Value, StringComparer.Ordinal)
            .ToImmutableArray();

        return new CatalogModel(keys, manifestEntries, providerEntries, cultures, sourceFiles, diagnostics.ToImmutable());
    }

    private static ImmutableArray<KeyIdentifier> CreateIdentifiers(ImmutableArray<string> keys)
    {
        var baseNames = keys
            .Select(static key => new KeyIdentifier(key, CreateIdentifier(key)))
            .ToArray();

        var collisions = baseNames
            .GroupBy(identifier => identifier.Name, StringComparer.Ordinal)
            .Where(group => group.Count() > 1)
            .Select(group => group.Key)
            .ToImmutableHashSet(StringComparer.Ordinal);

        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        var identifiers = ImmutableArray.CreateBuilder<KeyIdentifier>(baseNames.Length);

        foreach (KeyIdentifier identifier in baseNames)
        {
            string name = identifier.Name;
            if (collisions.Contains(name))
            {
                name = name + "_" + ComputeStableHash(identifier.Key);
            }

            while (!usedNames.Add(name))
            {
                name = name + "_Key";
            }

            identifiers.Add(new KeyIdentifier(identifier.Key, name));
        }

        return identifiers.ToImmutable();
    }

