    private sealed class JsonCatalogParser
    {
        private readonly string _path;
        private readonly SourceText _text;
        private readonly DiagnosticDescriptor _invalidJsonDescriptor;
        private readonly ImmutableArray<KeyEntry>.Builder _keys = ImmutableArray.CreateBuilder<KeyEntry>();
        private readonly ImmutableArray<Diagnostic>.Builder _diagnostics = ImmutableArray.CreateBuilder<Diagnostic>();
        private readonly bool _skipMetadataKeys;
        private readonly string? _culture;
        private string _content;
        private int _position;

        private JsonCatalogParser(string path, SourceText text, DiagnosticDescriptor invalidJsonDescriptor, bool skipMetadataKeys, string? culture)
        {
            _path = path;
            _text = text;
            _invalidJsonDescriptor = invalidJsonDescriptor;
            _skipMetadataKeys = skipMetadataKeys;
            _culture = string.IsNullOrWhiteSpace(culture) ? null : culture;
            _content = text.ToString();
        }

        public static CatalogFile Parse(string path, SourceText text, DiagnosticDescriptor invalidJsonDescriptor, bool skipMetadataKeys = false, string? culture = null)
        {
            var parser = new JsonCatalogParser(path, text, invalidJsonDescriptor, skipMetadataKeys, culture);
            parser.ParseRoot();
            return new CatalogFile(path, parser._keys.ToImmutable(), parser._diagnostics.ToImmutable());
        }

        private void ParseRoot()
        {
            SkipWhitespace();
            if (!TryConsume('{'))
            {
                AddInvalidJson("Expected root object.");
                return;
            }

            ParseObjectMembers(prefix: string.Empty);
            if (_diagnostics.Count > 0)
            {
                return;
            }

            SkipWhitespace();
            if (!IsEnd)
            {
                AddInvalidJson("Unexpected content after root object.");
            }
        }

        private void ParseObjectMembers(string prefix)
        {
            SkipWhitespace();
            if (TryConsume('}'))
            {
                return;
            }

            while (!IsEnd)
            {
                SkipWhitespace();
                int nameStart = _position;
                if (!TryParseString(out string? propertyName))
                {
                    AddInvalidJson("Expected property name.");
                    return;
                }

                SkipWhitespace();
                if (!TryConsume(':'))
                {
                    AddInvalidJson("Expected ':' after property name.");
                    return;
                }

                string key = prefix.Length == 0 ? propertyName : prefix + "." + propertyName;
                SkipWhitespace();

                if (_skipMetadataKeys && propertyName.StartsWith("@", StringComparison.Ordinal))
                {
                    if (!TrySkipJsonValue())
                    {
                        return;
                    }
                }
                else
                    if (TryConsume('{'))
                    {
                        ParseObjectMembers(key);
                    }
                    else if (Current == '"')
                    {
                        if (!TryParseString(out string? value))
                        {
                            return;
                        }

                        _keys.Add(new KeyEntry(key, _path, _text, nameStart, value, _culture));
                    }
                    else if (!TrySkipValue())
                    {
                        return;
                    }

                SkipWhitespace();
                if (TryConsume('}'))
                {
                    return;
                }

                if (!TryConsume(','))
                {
                    AddInvalidJson("Expected ',' or '}' after property value.");
                    return;
                }
            }

            AddInvalidJson("Unterminated object.");
        }

        private bool TryParseString(out string value)
        {
            value = string.Empty;
            if (!TryConsume('"'))
            {
                return false;
            }

            var builder = new StringBuilder();
            while (!IsEnd)
            {
                char character = _content[_position++];
                if (character == '"')
                {
                    value = builder.ToString();
                    return true;
                }

                if (character != '\\')
                {
                    builder.Append(character);
                    continue;
                }

                if (IsEnd)
                {
                    AddInvalidJson("Unterminated escape sequence.");
                    return false;
                }

                char escape = _content[_position++];
                switch (escape)
                {
                    case '"':
                    case '\\':
                    case '/':
                        builder.Append(escape);
                        break;
                    case 'b':
                        builder.Append('\b');
                        break;
                    case 'f':
                        builder.Append('\f');
                        break;
                    case 'n':
                        builder.Append('\n');
                        break;
                    case 'r':
                        builder.Append('\r');
                        break;
                    case 't':
                        builder.Append('\t');
                        break;
                    case 'u':
                        if (!TryParseUnicodeEscape(out char unicodeCharacter))
                        {
                            return false;
                        }

                        builder.Append(unicodeCharacter);
                        break;
                    default:
                        AddInvalidJson("Invalid string escape sequence.");
                        return false;
                }
            }

            AddInvalidJson("Unterminated string.");
            return false;
        }

        private bool TryParseUnicodeEscape(out char value)
        {
            value = '\0';
            if (_position + 4 > _content.Length)
            {
                AddInvalidJson("Incomplete unicode escape sequence.");
                return false;
            }

            int codePoint = 0;
            for (int i = 0; i < 4; i++)
            {
                int digit = HexValue(_content[_position + i]);
                if (digit < 0)
                {
                    AddInvalidJson("Invalid unicode escape sequence.");
                    return false;
                }

                codePoint = (codePoint << 4) + digit;
            }

            _position += 4;
            value = (char)codePoint;
            return true;
        }

        private bool TrySkipValue()
        {
            if (TryConsume('['))
            {
                return TrySkipArray();
            }

            if (TryConsume('{'))
            {
                return TrySkipObject();
            }

            if (TryConsumeLiteral("true") || TryConsumeLiteral("false") || TryConsumeLiteral("null"))
            {
                return true;
            }

            return TrySkipNumber();
        }

        private bool TrySkipJsonValue()
        {
            SkipWhitespace();
            if (IsEnd)
            {
                AddInvalidJson("Expected value.");
                return false;
            }

            if (Current == '"')
            {
                return TryParseString(out _);
            }

            if (TryConsume('{'))
            {
                return TrySkipObject();
            }

            if (TryConsume('['))
            {
                return TrySkipArray();
            }

            if (TryConsumeLiteral("true") || TryConsumeLiteral("false") || TryConsumeLiteral("null"))
            {
                return true;
            }

            return TrySkipNumber();
        }

        private bool TrySkipObject()
        {
            SkipWhitespace();
            if (TryConsume('}'))
            {
                return true;
            }

            while (!IsEnd)
            {
                SkipWhitespace();
                if (!TryParseString(out _))
                {
                    AddInvalidJson("Expected property name.");
                    return false;
                }

                SkipWhitespace();
                if (!TryConsume(':'))
                {
                    AddInvalidJson("Expected ':' after property name.");
                    return false;
                }

                if (!TrySkipJsonValue())
                {
                    return false;
                }

                SkipWhitespace();
                if (TryConsume('}'))
                {
                    return true;
                }

                if (!TryConsume(','))
                {
                    AddInvalidJson("Expected ',' or '}' after property value.");
                    return false;
                }
            }

            AddInvalidJson("Unterminated object.");
            return false;
        }

        private bool TrySkipArray()
        {
            SkipWhitespace();
            if (TryConsume(']'))
            {
                return true;
            }

            while (!IsEnd)
            {
                if (!TrySkipJsonValue())
                {
                    return false;
                }

                SkipWhitespace();
                if (TryConsume(']'))
                {
                    return true;
                }

                if (!TryConsume(','))
                {
                    AddInvalidJson("Expected ',' or ']' after array value.");
                    return false;
                }
            }

            AddInvalidJson("Unterminated array.");
            return false;
        }

        private bool TryConsumeLiteral(string literal)
        {
            if (_position + literal.Length > _content.Length)
            {
                return false;
            }

            for (int i = 0; i < literal.Length; i++)
            {
                if (_content[_position + i] != literal[i])
                {
                    return false;
                }
            }

            _position += literal.Length;
            return true;
        }

        private bool TrySkipNumber()
        {
            int start = _position;

            if (!IsEnd && Current == '-')
            {
                _position++;
            }

            if (IsEnd || !char.IsDigit(Current))
            {
                _position = start;
                AddInvalidJson("Expected value.");
                return false;
            }

            if (Current == '0')
            {
                _position++;
            }
            else
            {
                while (!IsEnd && char.IsDigit(Current))
                {
                    _position++;
                }
            }

            if (!IsEnd && Current == '.')
            {
                _position++;
                if (IsEnd || !char.IsDigit(Current))
                {
                    AddInvalidJson("Expected digit after decimal point.");
                    return false;
                }

                while (!IsEnd && char.IsDigit(Current))
                {
                    _position++;
                }
            }

            if (!IsEnd && (Current == 'e' || Current == 'E'))
            {
                _position++;
                if (!IsEnd && (Current == '+' || Current == '-'))
                {
                    _position++;
                }

                if (IsEnd || !char.IsDigit(Current))
                {
                    AddInvalidJson("Expected exponent digit.");
                    return false;
                }

                while (!IsEnd && char.IsDigit(Current))
                {
                    _position++;
                }
            }

            return true;
        }

        private void SkipWhitespace()
        {
            while (!IsEnd && char.IsWhiteSpace(Current))
            {
                _position++;
            }
        }

        private bool TryConsume(char expected)
        {
            if (IsEnd || Current != expected)
            {
                return false;
            }

            _position++;
            return true;
        }

        private void AddInvalidJson(string message)
        {
            _diagnostics.Add(Diagnostic.Create(
                _invalidJsonDescriptor,
                CreateLocation(_path, _text, Math.Min(_position, Math.Max(0, _content.Length - 1))),
                Path.GetFileName(_path),
                message));
        }

        private char Current => _content[_position];

        private bool IsEnd => _position >= _content.Length;

        private static int HexValue(char character)
        {
            if (character >= '0' && character <= '9')
            {
                return character - '0';
            }

            if (character >= 'a' && character <= 'f')
            {
                return character - 'a' + 10;
            }

            if (character >= 'A' && character <= 'F')
            {
                return character - 'A' + 10;
            }

            return -1;
        }
    }

    private static Location CreateLocation(string path, SourceText text, int position)
    {
        int safePosition = Math.Max(0, Math.Min(position, text.Length));
        var span = new TextSpan(safePosition, safePosition < text.Length ? 1 : 0);
        return Location.Create(path, span, text.Lines.GetLinePositionSpan(span));
    }

    private static Diagnostic CreateInvalidJsonDiagnostic(string path, SourceText text, int position, string message) =>
        Diagnostic.Create(
            InvalidJsonDescriptor,
            CreateLocation(path, text, position),
            Path.GetFileName(path),
            message);

    private readonly struct CatalogModel
    {
        public CatalogModel(
            ImmutableArray<string> keys,
            ImmutableArray<ManifestEntry> manifestEntries,
            ImmutableArray<ProviderEntry> providerEntries,
            ImmutableArray<string> cultures,
            ImmutableArray<string> sourceFiles,
            ImmutableArray<Diagnostic> diagnostics)
        {
            Keys = keys;
            ManifestEntries = manifestEntries;
            ProviderEntries = providerEntries;
            Cultures = cultures;
            SourceFiles = sourceFiles;
            Diagnostics = diagnostics;
        }

        public ImmutableArray<string> Keys { get; }

        public ImmutableArray<ManifestEntry> ManifestEntries { get; }

        public ImmutableArray<ProviderEntry> ProviderEntries { get; }

        public ImmutableArray<string> Cultures { get; }

        public ImmutableArray<string> SourceFiles { get; }

        public ImmutableArray<Diagnostic> Diagnostics { get; }
    }

    private readonly struct CatalogFile
    {
        public CatalogFile(string path, ImmutableArray<KeyEntry> keys, ImmutableArray<Diagnostic> diagnostics)
        {
            Path = path;
            Keys = keys;
            Diagnostics = diagnostics;
        }

        public string Path { get; }

        public ImmutableArray<KeyEntry> Keys { get; }

        public ImmutableArray<Diagnostic> Diagnostics { get; }
    }

    private readonly struct KeyEntry
    {
        public KeyEntry(string key, string path, SourceText text, int position, string? value = null, string? culture = null)
        {
            Key = key;
            SourceFile = path;
            Culture = culture ?? InferCulture(path);
            PlaceholderIndexes = value is null ? ImmutableArray<int>.Empty : ExtractPlaceholderIndexes(value);
            Value = value;
            Location = CreateLocation(path, text, position);
        }

        public string Key { get; }

        public string SourceFile { get; }

        public string? Culture { get; }

        public ImmutableArray<int> PlaceholderIndexes { get; }

        public string? Value { get; }

        public Location Location { get; }

        public ManifestEntry ToManifestEntry() => new(Key, Culture, SourceFile, PlaceholderIndexes);
    }

