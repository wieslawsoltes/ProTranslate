namespace ProTranslate.SourceGenerator;

/// <summary>
/// Generates strongly typed key catalogs from ProTranslate AdditionalFiles.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ProTranslateKeysGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidJsonDescriptor = new(
        "PTSG001",
        "Invalid ProTranslate JSON catalog",
        "Could not parse ProTranslate JSON catalog '{0}': {1}",
        "ProTranslate.SourceGenerator",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DuplicateKeyDescriptor = new(
        "PTSG002",
        "Duplicate ProTranslate key",
        "Translation key '{0}' is declared more than once in '{1}'",
        "ProTranslate.SourceGenerator",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<CatalogFile> catalogFiles = context.AdditionalTextsProvider
            .Where(static file => IsCatalogFile(file.Path))
            .Select(static (file, cancellationToken) => ParseCatalogFile(file, cancellationToken));

        IncrementalValueProvider<CatalogModel> catalog = catalogFiles
            .Collect()
            .Select(static (files, _) => CreateCatalogModel(files));

        context.RegisterSourceOutput(catalog, static (sourceContext, model) =>
        {
            foreach (Diagnostic diagnostic in model.Diagnostics)
            {
                sourceContext.ReportDiagnostic(diagnostic);
            }

            if (model.Keys.IsDefaultOrEmpty)
            {
                return;
            }

            sourceContext.AddSource("ProTranslateKeys.g.cs", SourceText.From(Render(model.Keys), Encoding.UTF8));
            sourceContext.AddSource("ProTranslateStrings.g.cs", SourceText.From(RenderStrings(model.Keys), Encoding.UTF8));
            sourceContext.AddSource("ProTranslateProviderManifest.g.cs", SourceText.From(RenderManifest(model), Encoding.UTF8));
            sourceContext.AddSource("ProTranslateGeneratedTranslationProvider.g.cs", SourceText.From(RenderGeneratedProvider(model), Encoding.UTF8));
        });
    }

    private static string Render(ImmutableArray<string> keys)
    {
        ImmutableArray<KeyIdentifier> identifiers = CreateIdentifiers(keys);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("namespace ProTranslate.Generated;");
        builder.AppendLine();
        builder.AppendLine("public static partial class ProTranslateKeys");
        builder.AppendLine("{");

        foreach (KeyIdentifier identifier in identifiers)
        {
            builder.Append("    public const string ");
            builder.Append(identifier.Name);
            builder.Append(" = ");
            builder.Append(FormatStringLiteral(identifier.Key));
            builder.AppendLine(";");
        }

        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("public static partial class ProTranslateAccessors");
        builder.AppendLine("{");

        foreach (KeyIdentifier identifier in identifiers)
        {
            builder.Append("    public static ProTranslate.LocalizedString ");
            builder.Append("Get_");
            builder.Append(identifier.Name);
            builder.AppendLine("(this ProTranslate.ITranslationService translations) =>");
            builder.Append("        translations.GetString(ProTranslateKeys.");
            builder.Append(identifier.Name);
            builder.AppendLine(");");
            builder.AppendLine();

            builder.Append("    public static string ");
            builder.Append("Value_");
            builder.Append(identifier.Name);
            builder.AppendLine("(this ProTranslate.ITranslationService translations) =>");
            builder.Append("        translations.GetString(ProTranslateKeys.");
            builder.Append(identifier.Name);
            builder.AppendLine(").Value;");
            builder.AppendLine();

            builder.Append("    public static string Format");
            builder.Append("_");
            builder.Append(identifier.Name);
            builder.AppendLine("(this ProTranslate.ITranslationService translations, params object?[] arguments) =>");
            builder.Append("        translations.Format(ProTranslateKeys.");
            builder.Append(identifier.Name);
            builder.AppendLine(", arguments);");
            builder.AppendLine();

            builder.Append("    public static ProTranslate.IObservableLocalizedString Observe");
            builder.Append("_");
            builder.Append(identifier.Name);
            builder.AppendLine("(this ProTranslate.ITranslationService translations, params object?[] arguments) =>");
            builder.Append("        translations.Observe(ProTranslateKeys.");
            builder.Append(identifier.Name);
            builder.AppendLine(", arguments);");
            builder.AppendLine();
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

